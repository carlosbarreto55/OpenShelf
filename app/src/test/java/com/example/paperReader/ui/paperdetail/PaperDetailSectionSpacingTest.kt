/**
 * The detail screen leaves no blank area between its sections beyond the spacing tokens. The
 * paper is shaped like the live backend's, three long topics included, because that is what
 * opened the gap: the demo catalog's single short topic per paper never did.
 */
@RunWith(RobolectricTestRunner::class)
// Phone width, and tall enough that every section is laid out without scrolling.
@Config(sdk = [34], qualifiers = "w412dp-h2000dp")
// Real text measurement, without which no label is wide enough to wrap.
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class PaperDetailSectionSpacingTest {
    @get:Rule
    val composeRule = createComposeRule()

    private val spacing = PaperReaderSpacing()

    @Test
    fun consecutiveSectionsAreOneCardSpacingApart() {
        setContent()

        val authors = composeRule.onNodeWithText(AUTHORS).getUnclippedBoundsInRoot()
        val metadata = composeRule.onNodeWithText(METADATA, substring = true).getUnclippedBoundsInRoot()
        val topics = composeRule.onNodeWithTag(PAPER_DETAIL_TOPICS_TEST_TAG).getUnclippedBoundsInRoot()
        val abstractHeading = composeRule.onNodeWithText("Abstract").getUnclippedBoundsInRoot()

        assertGap(spacing.card, authors, metadata, "authors → metadata")
        assertGap(spacing.card, metadata, topics, "metadata → topics")
        assertGap(spacing.card, topics, abstractHeading, "topics → abstract")
    }

    @Test
    fun theTopicSectionIsOnlyAsTallAsItsLinesOfPills() {
        setContent()

        val labels = TOPICS.map { composeRule.onNodeWithText(it) }
        labels.forEach { assertEquals("one line per label", 1, it.textLayout().lineCount) }

        val bounds = labels.map { it.getUnclippedBoundsInRoot() }
        val pillHeight = bounds.first().height + spacing.control * 2
        val lines = bounds.map { it.top }.distinct().size
        val expected = pillHeight * lines + spacing.control * (lines - 1)
        val actual = composeRule.onNodeWithTag(PAPER_DETAIL_TOPICS_TEST_TAG).getUnclippedBoundsInRoot().height
        assertEquals(expected.value, actual.value, TOLERANCE_DP)
    }

    private fun assertGap(expected: Dp, above: DpRect, below: DpRect, between: String) {
        assertEquals(between, expected.value, (below.top - above.bottom).value, TOLERANCE_DP)
    }

    private fun setContent() {
        composeRule.setContent {
            PaperReaderTheme {
                PaperDetailScreen(
                    state = PaperDetailUiState(
                        content = PaperDetailContent.Loaded(
                            paper = Paper(
                                id = PaperId("W2741809807"),
                                title = "Harnessing Generative AI for Automated Feedback in Higher Education",
                                authors = listOf(Author("R. M. Mahoney"), Author("A. Chen")),
                                venue = "Online Learning",
                                publicationYear = 2024,
                                type = PaperType.REVIEW,
                                topics = TOPICS.map(::Topic),
                                citationCount = 151,
                                abstractText = "Automated feedback is increasingly generated by language models.",
                                access = AccessResolution.NoFreeFullText,
                            ),
                        ),
                    ),
                    onBack = {},
                    onRetry = {},
                    onToggleSave = {},
                    onReadPdf = {},
                    onReadOnline = {},
                )
            }
        }
    }

    private fun SemanticsNodeInteraction.textLayout(): TextLayoutResult {
        val results = mutableListOf<TextLayoutResult>()
        fetchSemanticsNode().config[SemanticsActions.GetTextLayoutResult].action?.invoke(results)
        return results.single()
    }

    private companion object {
        const val AUTHORS = "R. M. Mahoney, A. Chen"
        const val METADATA = "Online Learning · 2024"

        /** A paper's topics exactly as the live backend returned them for "machine learning". */
        val TOPICS = listOf(
            "Machine Learning and Algorithms",
            "Domain Adaptation and Few-Shot Learning",
            "Neural Networks and Applications",
        )

        /** Sub-pixel rounding between density conversions, nothing a reader could see. */
        const val TOLERANCE_DP = 0.5f
    }
}
